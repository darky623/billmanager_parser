def resolve_location(raw: str) -> str | None:
    """Determine ISO country code from a raw location string.

    Exact copy of cloudsell_api/gateways/providers/mapings.py::resolve_location.
    First tries an exact match (lowercased), then searches for any known
    keyword as a substring inside *raw*. Longer keywords are checked first
    so that e.g. "нижний новгород" matches before "новгород".
    """
    if not raw:
        return None
    lowered = raw.lower().strip()

    if lowered in LOCATION_MAPPING:
        return LOCATION_MAPPING[lowered]

    for key in sorted(LOCATION_MAPPING, key=len, reverse=True):
        if key in lowered:
            return LOCATION_MAPPING[key]

    return None
